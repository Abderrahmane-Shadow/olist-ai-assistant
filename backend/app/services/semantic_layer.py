class SemanticLayer:
    """Semantic Layer catalog providing business metrics, join paths, and aggregation rules for LLM generation."""

    def __init__(self):
        self.metrics = SEMANTIC_METRICS
        self.dimensions = SEMANTIC_DIMENSIONS
        self.joins = CANONICAL_JOINS
        self.guardrails = AGGREGATION_GUARDRAILS

    def format_semantic_layer_for_llm(self) -> str:
        """Render clean, compact semantic rules for LLM prompt injection."""
        lines = [
            "CANONICAL BUSINESS METRICS (Formulas & Aggregation):",
        ]
        for m in self.metrics.values():
            lines.append(f"- {m.label} ({m.name}): {m.formula} [{m.unit}] -> {m.description}")

        lines.append("\nVALIDATED JOIN RELATIONSHIPS (Use strictly these join keys):")
        for j in self.joins:
            lines.append(f"- {j.join_type} JOIN {j.to_table} ON {j.condition}")

        lines.append("\nCANONICAL ANALYTICAL DIMENSIONS:")
        for d in self.dimensions.values():
            lines.append(f"- {d.label} ({d.name}): {d.expression} (from {d.table})")

        lines.append("\nCRITICAL AGGREGATION GUARDRAILS:")
        for idx, g in enumerate(self.guardrails, 1):
            lines.append(f"{idx}. {g}")

        return "\n".join(lines)


_global_semantic_layer: Optional[SemanticLayer] = None


def get_semantic_layer() -> SemanticLayer:
    """Dependency helper for singleton SemanticLayer."""
    global _global_semantic_layer
    if _global_semantic_layer is None:
        _global_semantic_layer = SemanticLayer()
    return _global_semantic_layer
