"""Declarative Semantic Layer for Olist AI Assistant.

Provides centralized business logic, metric definitions, dimension definitions,
canonical join relationships, multilingual business terminology, and aggregation
rules for dynamic Text-to-SQL generation.

Does NOT store individual question-to-SQL mappings.
"""

import logging
from dataclasses import dataclass, field
from typing import Dict, List, Optional

logger = logging.getLogger("olist.services.semantic_layer")


@dataclass
class SemanticMetric:
    """Definition of a canonical business metric."""
    name: str
    label: str
    formula: str
    unit: str
    description: str
    synonyms_en: List[str]
    synonyms_fr: List[str]
    synonyms_pt: List[str]
    aggregation_rule: str
    required_tables: List[str]


@dataclass
class SemanticDimension:
    """Definition of an analytical business dimension."""
    name: str
    label: str
    expression: str
    description: str
    synonyms_en: List[str]
    synonyms_fr: List[str]
    synonyms_pt: List[str]
    table: str


@dataclass
class JoinPath:
    """Validated join path between two tables."""
    from_table: str
    to_table: str
    join_type: str  # INNER, LEFT
    condition: str
    description: str


